namespace AssignmentNine.Model.Enum
{
    /// <summary>
    /// Represent the Filter operations.
    /// </summary>
    public enum FilterOperation
    {
        /// <summary>
        /// Contains operation
        /// </summary>
        Contains = 1,

        /// <summary>
        /// StartsWith operation
        /// </summary>
        StartsWith,

        /// <summary>
        /// EndsWith operation
        /// </summary>
        EndsWith,

        /// <summary>
        /// Greater than or equal to operation
        /// </summary>
        GreaterThanOrEqualTo,

        /// <summary>
        /// Less than or equal to operation
        /// </summary>
        LessThanEqualTo,
    }
}
